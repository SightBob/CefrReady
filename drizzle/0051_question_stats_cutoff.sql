-- ค่าเริ่มต้น NULL ทุกแถว: ยังไม่มีพฤติกรรมเปลี่ยนจนกว่าจะตั้งค่าให้ข้อที่แก้แล้ว
ALTER TABLE "questions" ADD COLUMN IF NOT EXISTS "stats_cutoff_at" timestamp;
